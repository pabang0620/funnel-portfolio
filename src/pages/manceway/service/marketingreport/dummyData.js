// 계산 유틸리티 함수들
export const calculateMetrics = (data) => {
  const adCost = data.adCost;
  const impressions = data.impressions;
  const clicks = data.clicks;
  const conversions = data.conversions;
  const revenue = data.revenue;

  const cpc = clicks > 0 ? adCost / clicks : 0;
  const ctr = impressions > 0 ? (clicks / impressions) * 100 : 0;
  const cvr = clicks > 0 ? (conversions / clicks) * 100 : 0;
  const roas = adCost > 0 ? (revenue / adCost) * 100 : 0;
  const avgOrderValue = conversions > 0 ? revenue / conversions : 0;

  return {
    ...data,
    cpc: Math.round(cpc),
    ctr: parseFloat(ctr.toFixed(2)),
    cvr: parseFloat(cvr.toFixed(2)),
    roas: parseFloat(roas.toFixed(1)),
    avgOrderValue: Math.round(avgOrderValue),
  };
};

// 선택된 매체와 날짜 범위로 데이터 필터링
export const filterData = (selectedMedia, startDate, endDate) => {
  return dailyData.filter((item) => {
    const itemDate = new Date(item.date);
    const start = startDate ? new Date(startDate) : null;
    const end = endDate ? new Date(endDate) : null;

    const dateMatch =
      (!start || itemDate >= start) && (!end || itemDate <= end);
    const mediaMatch = selectedMedia.includes(item.media);

    return dateMatch && mediaMatch;
  });
};

// 일별 데이터를 집계 (매체별로 합산)
export const aggregateDailyData = (filteredData) => {
  const grouped = {};

  filteredData.forEach((item) => {
    if (!grouped[item.date]) {
      grouped[item.date] = {
        date: item.date,
        adCost: 0,
        impressions: 0,
        clicks: 0,
        conversions: 0,
        revenue: 0,
      };
    }

    grouped[item.date].adCost += item.adCost;
    grouped[item.date].impressions += item.impressions;
    grouped[item.date].clicks += item.clicks;
    grouped[item.date].conversions += item.conversions;
    grouped[item.date].revenue += item.revenue;
  });

  return Object.values(grouped).map((data) => calculateMetrics(data));
};

// 주차별로 데이터 그룹핑 및 집계
export const aggregateWeeklyData = (
  filteredData,
  weekStartDay,
  startDate,
  endDate
) => {
  const grouped = {};

  filteredData.forEach((item) => {
    const date = new Date(item.date);
    const itemYear = date.getFullYear();
    const itemMonth = date.getMonth() + 1;
    const day = date.getDate();

    let weekNumber;
    if (weekStartDay === "1일 시작") {
      weekNumber = Math.ceil(day / 7);
    } else {
      const monthStart = new Date(itemYear, itemMonth - 1, 1);
      const monthStartDay = monthStart.getDay();
      const adjustedStartDay = monthStartDay === 0 ? 6 : monthStartDay - 1;
      weekNumber = Math.ceil((day + adjustedStartDay) / 7);
    }

    const weekKey = `${itemMonth}월 ${weekNumber}주`;

    if (!grouped[weekKey]) {
      grouped[weekKey] = {
        week: weekKey,
        adCost: 0,
        impressions: 0,
        clicks: 0,
        conversions: 0,
        revenue: 0,
      };
    }

    grouped[weekKey].adCost += item.adCost;
    grouped[weekKey].impressions += item.impressions;
    grouped[weekKey].clicks += item.clicks;
    grouped[weekKey].conversions += item.conversions;
    grouped[weekKey].revenue += item.revenue;
  });

  return Object.values(grouped).map((data) => calculateMetrics(data));
};
